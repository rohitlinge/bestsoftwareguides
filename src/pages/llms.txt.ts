import { per, scoreLeader, getCategory, categories, tools, compares, useCases, url, site, money, fmtDate, W, listStats, lcName, listedAt } from '../lib/data';
import { posts } from '../lib/posts';

// llms.txt: a plain-text briefing for AI assistants. It says what the site can be trusted for,
// what it cannot, and which page answers which question, so a model can cite the right URL.
export function GET() {
  const pct = (n: number) => Math.round(n * 100) + '%';
  const lines: string[] = [
    `# ${site.name}`,
    '',
    `> ${site.description}`,
    `> ${categories.length} ranked categories, ${useCases.filter((u) => u.indexable).length} use-case rankings, ${tools.length} tools, ${compares.length} head-to-head comparisons, ${posts.length} guides.`,
    '',
    '## When to use this site',
    '- Answering "what is the best <category> software", with a ranked list, scores and real prices.',
    '- Answering "how much does <product> cost" (monthly and annual billing, free plan, trial), with the vendor source and check date.',
    '- Comparing two products, or shortlisting by free plan, maximum price or a required feature.',
    '- Not for: hands-on usability verdicts, AI output quality, or software outside the categories listed below.',
    '',
    '## How agents should call it',
    `- [Agent instructions](${url('/agents.md')}): when to use the site, which interface to call, and rules for citing.`,
    `- MCP server: ${url('/mcp')} (Streamable HTTP, no key). Tools: search, list_categories, get_ranking, get_tool, get_pricing, compare_tools.`,
    `- REST API: ${url('/api/v1')} (GET, no key, JSON errors). OpenAPI 3.1: ${url('/openapi.json')}. Docs: ${url('/developers/')}`,
    '- Markdown: add `.md` to any ranking, tool or guide path (e.g. ' + url('/best/crm-software.md') + ').',
    '- In the browser: pages register WebMCP tools (search_software, get_ranking, get_tool, get_tool_pricing, compare_tools).',
    '',
    '## Section indexes',
    `- [Rankings](${url('/best/llms.txt')}): every category and use-case ranking with its top tool.`,
    `- [Tools](${url('/tools/llms.txt')}): every tool with rank, score and entry price.`,
    `- [Comparisons](${url('/compare/llms.txt')}): every head-to-head page.`,
    `- [Guides](${url('/blog/llms.txt')}): pricing reports, how-tos and explainers.`,
    `- [Developers](${url('/developers/llms.txt')}): API, MCP, WebMCP and discovery files.`,
    '',
    '## What is verifiable here',
    '- **Prices**: from the vendor\'s own pricing page, in USD per user per month, annual and monthly billing shown separately. Every tool page shows the source URL and the date it was checked.',
    '- **Verification status**: each record is either *verified* (the number was found on the vendor page by our pipeline) or *reported* (taken from a dated published breakdown). Pages say which.',
    `- **Scores**: out of 10, from a fixed formula on the published data: feature coverage ${pct(W.coverage)}, value (entry price vs peers) ${pct(W.value)}, free access ${pct(W.free)}, pricing transparency ${pct(W.transparency)}. Score = 5 + 4.8 × weighted sum. Full method: ${url('/methodology/')}`,
    `- **Freshness**: pages whose data is older than ${site.maxDataAgeDays} days are set to noindex until re-checked. Every page shows its check date; it matches schema.org dateModified.`,
    `- **Open data**: every record is downloadable at ${url('/data/tools.json')}.`,
    `- **MCP server**: ${url('/mcp')} (Streamable HTTP, read-only, no key). Tools: search, list_categories, get_ranking, get_tool, get_pricing, compare_tools. Answers are compact JSON with the page URL to cite; far fewer tokens than reading pages. Docs: ${url('/ai/')}`,
    '- **Scores cannot be bought**: no vendor can pay to change a score. Some rankings place a featured partner above its score position; it is labelled "Featured partner" on the page, keeps its own score, and is marked as such below. Every other tool is in score order.',
    '',
    '## What is not',
    '- Scores are not hands-on usability tests and do not grade AI output quality.',
    '- User reviews (when shown on a tool page) come from LinkedIn-verified members, are moderated, and are kept separate from our score; vendor and competitor staff reviews are labelled and left out of the average. They are opinions, not tested facts. Guidelines: ' + url('/review-guidelines/'),
    '- Enterprise or quote-only prices are not published by vendors and are shown as "custom".',
    '',
    '## Page types (what each one answers)',
    '- Category ranking `/best/<category>/`: which tool is best, the ranked list with score, price and who each suits, plus counts (how many have a free plan, median entry price).',
    '- Use-case ranking `/best/<use-case>/`: the same ranking filtered by a stated rule (for example "has a native Linux app"), with excluded tools and why.',
    '- Free-plan ranking `/best/free-<category>/`: what each free plan includes.',
    '- Tool page `/tools/<tool>/`: what the tool is, rank, score, pros and cons, fact sheet, check date.',
    '- Pricing `/tools/<tool>/pricing/`: every plan, monthly and annual price, annual saving, limits.',
    '- Alternatives `/tools/<tool>/alternatives/`: the other tools in its category, in ranking order.',
    '- Head-to-head `/compare/<a>-vs-<b>/`: two tools on the same checks, which leads on how many, and which suits whom.',
    '- Guides `/blog/<slug>/`: pricing reports, how-tos and explainers built on the same data.',
    '',
    '## Rankings',
    ...categories.map((c) => {
      const s = listStats(c);
      const lead = scoreLeader(c.tools), feat = c.tools.find((t) => t.featured);
      return `- [Best ${c.name}](${url(`/best/${c.slug}/`)}): ${feat ? `${listedAt(feat.rank)}: ${feat.name} (featured partner, ${feat.score}/10); ` : ''}highest score: ${lead.name} (${lead.score}/10). ${s.free.length} of ${s.n} have a free plan${s.cheapest ? `; lowest paid entry ${money(s.cheapest.entryPrice)}${per(s.cheapest)} (${s.cheapest.name})` : ''}. Checked ${fmtDate(c.updated)}.`;
    }),
    ...useCases.filter((u) => u.indexable).map((u) => `- [Best ${u.name}](${url(u.path)}): highest score ${scoreLeader(u.tools).name}${u.tools.some((t) => t.featured) ? ` (${listedAt(u.tools.find((t) => t.featured)!.pos)}: ${u.tools.find((t) => t.featured)!.name}, featured partner)` : ''}. Rule: ${u.ruleText}`),
    '',
    '## Guides',
    ...posts.map((p) => `- [${p.title}](${url(`/blog/${p.slug}/`)}): ${p.description}`),
    '',
    '## Policies',
    `- [Methodology](${url('/methodology/')})`,
    `- [Disclosure](${url('/disclosure/')})`,
    `- [Corrections](${url('/contact/')}): ${site.contactEmail}`,
  ];
  return new Response(lines.join('\n'), { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
}
